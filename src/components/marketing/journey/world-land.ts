function inside([x, y]: LonLat, polygon: readonly LonLat[]) {
  let hit = false;
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const [xi, yi] = polygon[i]!;
    const [xj, yj] = polygon[j]!;
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

/** Evenly spaced points on the sphere (Fibonacci lattice) that fall on land, in radians. */
export function landDots(samples = 9000): Float32Array {
  const out: number[] = [];
  const golden = Math.PI * (3 - Math.sqrt(5));
  for (let i = 0; i < samples; i++) {
    const y = 1 - (i / (samples - 1)) * 2;
    const lat = Math.asin(y);
    const lon = ((((i * golden) % (2 * Math.PI)) + 2 * Math.PI) % (2 * Math.PI)) - Math.PI;
    const point: LonLat = [(lon * 180) / Math.PI, (lat * 180) / Math.PI];
    if (LANDMASSES.some((land) => inside(point, land))) out.push(lat, lon);
  }
  return new Float32Array(out);
}
